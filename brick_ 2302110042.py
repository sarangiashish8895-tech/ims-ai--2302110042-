import math
from cadquery import func as cf

def clutch_brick(length, width, height, stud_d, stud_h, spacing):
    body = cf.box(length, width, height)
    stud = cf.cylinder(d=stud_d, h=stud_h)

    # Create 8 studs using nested for loops
    for i in range(4):
        for j in range(2):
            x = (i - 1.5) * spacing
            y = (j - 0.5) * spacing

            new_stud = stud.moved(x=x, y=y, z=height)
            body = body + new_stud

    return body

brick = clutch_brick(31.2, 15.6, 9.6, 4.8, 1.7, 7.8)

# Calculate expected volume
expected = (
    31.2 * 15.6 * 9.6
    + 8 * math.pi * (4.8 / 2) ** 2 * 1.7
)

assert abs(brick.Volume() - expected) < 0.5

# Export STL
brick.exportStl("brick_8_studs.stl")